pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len < 2) return error.InvalidArguments;

    if (std.mem.eql(u8, args[1], "serve")) {
        try mainServe(init.io, args);
        return;
    }
    if (std.mem.eql(u8, args[1], "echo")) {
        try mainEcho(init.io, args);
        return;
    }
    if (std.mem.eql(u8, args[1], "probe")) {
        const probe_name = try mainProbe(init.io, args);
        try printLine(
            init.io,
            "E2E_SS_UDP_PROBE_PASS={s}\n",
            .{probe_name},
        );
        return;
    }
    return error.InvalidArguments;
}

fn decodeLiteralHex(comptime hex: []const u8) ![hex.len / 2]u8 {
    var bytes: [hex.len / 2]u8 = undefined;
    _ = try std.fmt.hexToBytes(&bytes, hex);
    return bytes;
}

fn expectLiteralDatagramVector(
    comptime cipher: Cipher,
    comptime plaintext_hex: []const u8,
    comptime salt_hex: []const u8,
    comptime wire_hex: []const u8,
) !void {
    // These disjoint vectors are generated by the independent Node built-in
    // crypto procedure in scripts/e2e/generate-shadowsocks-udp-vectors.mjs.
    const plaintext = try decodeLiteralHex(plaintext_hex);
    const salt = try decodeLiteralHex(salt_hex);
    const expected_wire = try decodeLiteralHex(wire_hex);
    var crypto = DatagramCrypto.init(cipher, "oracle-vector-password-v1");
    defer crypto.deinit();

    var wire_buffer: [expected_wire.len]u8 = undefined;
    const wire = try crypto.sealWithSalt(&plaintext, &salt, &wire_buffer);
    try std.testing.expectEqualSlices(u8, &expected_wire, wire);

    var plaintext_buffer: [plaintext.len]u8 = undefined;
    const opened = try crypto.open(&expected_wire, &plaintext_buffer);
    try std.testing.expectEqualSlices(u8, &plaintext, opened);
}

