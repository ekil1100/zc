const Deadline = struct {
    expires_ms: i64,

    fn after(io: std.Io, duration_ms: i64) Deadline {
        std.debug.assert(duration_ms > 0);
        return .{
            .expires_ms = std.math.add(
                i64,
                monotonicMs(io),
                duration_ms,
            ) catch std.math.maxInt(i64),
        };
    }

    fn limited(self: Deadline, io: std.Io, duration_ms: i64) Deadline {
        const shorter = Deadline.after(io, duration_ms);
        return .{ .expires_ms = @min(self.expires_ms, shorter.expires_ms) };
    }

    fn remaining(self: Deadline, io: std.Io) !i32 {
        const now_ms = monotonicMs(io);
        if (now_ms >= self.expires_ms) return error.DeadlineExceeded;
        const difference = std.math.sub(
            i64,
            self.expires_ms,
            now_ms,
        ) catch return error.DeadlineExceeded;
        return @intCast(@min(difference, std.math.maxInt(i32)));
    }
};

fn monotonicMs(io: std.Io) i64 {
    return @intCast(@divTrunc(
        std.Io.Timestamp.now(io, .awake).nanoseconds,
        std.time.ns_per_ms,
    ));
}

fn waitFd(
    io: std.Io,
    fd: std.posix.fd_t,
    requested: i16,
    deadline: Deadline,
) !i16 {
    for (0..syscall_retry_max) |_| {
        const timeout_ms = deadline.remaining(io) catch |err| switch (err) {
            error.DeadlineExceeded => return 0,
        };
        var descriptor = [_]std.posix.pollfd{.{
            .fd = fd,
            .events = requested,
            .revents = 0,
        }};
        const result = std.c.poll(&descriptor, 1, timeout_ms);
        if (result == 0) {
            if (monotonicMs(io) >= deadline.expires_ms) return 0;
            continue;
        }
        if (result < 0) {
            switch (std.c.errno(result)) {
                .INTR => continue,
                .NOMEM => return error.SystemResources,
                else => return error.PollFailed,
            }
        }
        const events = descriptor[0].revents;
        if (events & std.posix.POLL.NVAL != 0) return error.InvalidSocket;
        if (events & (requested | std.posix.POLL.ERR |
            std.posix.POLL.HUP) == 0)
        {
            return error.UnexpectedPollEvent;
        }
        return events;
    }
    return error.SyscallRetryLimitExceeded;
}

fn waitFdPair(
    io: std.Io,
    first_fd: std.posix.fd_t,
    second_fd: std.posix.fd_t,
    deadline: Deadline,
) ![2]i16 {
    for (0..syscall_retry_max) |_| {
        const timeout_ms = deadline.remaining(io) catch |err| switch (err) {
            error.DeadlineExceeded => return .{ 0, 0 },
        };
        var descriptors = [_]std.posix.pollfd{
            .{ .fd = first_fd, .events = std.posix.POLL.IN, .revents = 0 },
            .{ .fd = second_fd, .events = std.posix.POLL.IN, .revents = 0 },
        };
        const result = std.c.poll(&descriptors, 2, timeout_ms);
        if (result == 0) {
            if (monotonicMs(io) >= deadline.expires_ms) return .{ 0, 0 };
            continue;
        }
        if (result < 0) {
            switch (std.c.errno(result)) {
                .INTR => continue,
                .NOMEM => return error.SystemResources,
                else => return error.PollFailed,
            }
        }
        for (descriptors) |descriptor| {
            if (descriptor.revents & std.posix.POLL.NVAL != 0) {
                return error.InvalidSocket;
            }
        }
        return .{ descriptors[0].revents, descriptors[1].revents };
    }
    return error.SyscallRetryLimitExceeded;
}

fn configureSocket(fd: std.posix.fd_t) !void {
    if (comptime builtin.os.tag.isDarwin()) {
        comptime if (!@hasDecl(std.c.SO, "NOSIGPIPE")) {
            @compileError("Darwin oracle sockets require SO_NOSIGPIPE");
        };
        var enabled: c_int = 1;
        if (std.c.setsockopt(
            fd,
            std.c.SOL.SOCKET,
            std.c.SO.NOSIGPIPE,
            std.mem.asBytes(&enabled),
            @sizeOf(c_int),
        ) != 0) return error.SocketSetupFailed;
    }

    const status_flags = std.c.fcntl(
        fd,
        std.posix.F.GETFL,
        @as(c_int, 0),
    );
    if (status_flags < 0) return error.SocketSetupFailed;
    const nonblocking: c_int = @bitCast(@as(u32, @bitCast(std.posix.O{
        .NONBLOCK = true,
    })));
    if (std.c.fcntl(
        fd,
        std.posix.F.SETFL,
        status_flags | nonblocking,
    ) < 0) return error.SocketSetupFailed;

    const descriptor_flags = std.c.fcntl(
        fd,
        std.posix.F.GETFD,
        @as(c_int, 0),
    );
    if (descriptor_flags < 0) return error.SocketSetupFailed;
    if (std.c.fcntl(
        fd,
        std.posix.F.SETFD,
        descriptor_flags | std.posix.FD_CLOEXEC,
    ) < 0) return error.SocketSetupFailed;
}

fn socketAddress4(endpoint: Endpoint4) std.c.sockaddr.in {
    var address = std.mem.zeroes(std.c.sockaddr.in);
    address.family = std.c.AF.INET;
    address.port = std.mem.nativeToBig(u16, endpoint.port);
    @memcpy(std.mem.asBytes(&address.addr)[0..4], &endpoint.ip);
    return address;
}

fn requireSocketBuffer(
    fd: std.posix.fd_t,
    option: u32,
    requested_size: c_int,
    minimum_size: c_int,
) !void {
    std.debug.assert(requested_size >= minimum_size);
    if (std.c.setsockopt(
        fd,
        std.c.SOL.SOCKET,
        option,
        std.mem.asBytes(&requested_size),
        @sizeOf(c_int),
    ) != 0) return error.SocketSetupFailed;

    var actual_size: c_int = 0;
    var actual_size_len: std.c.socklen_t = @sizeOf(c_int);
    if (std.c.getsockopt(
        fd,
        std.c.SOL.SOCKET,
        option,
        std.mem.asBytes(&actual_size).ptr,
        &actual_size_len,
    ) != 0) return error.SocketSetupFailed;
    if (actual_size_len != @sizeOf(c_int) or actual_size < minimum_size) {
        return error.SocketBufferTooSmall;
    }
}

fn configureUdpBuffers(fd: std.posix.fd_t) !void {
    const send_size = std.math.cast(c_int, wire_size_max) orelse
        return error.SocketSetupFailed;
    const receive_size = std.math.cast(c_int, 262_144) orelse
        return error.SocketSetupFailed;
    const receive_minimum = std.math.cast(c_int, receive_size_max) orelse
        return error.SocketSetupFailed;
    try requireSocketBuffer(fd, std.c.SO.SNDBUF, send_size, send_size);
    try requireSocketBuffer(
        fd,
        std.c.SO.RCVBUF,
        receive_size,
        receive_minimum,
    );
}

