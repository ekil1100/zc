fn createUdpSocketAt(ip: [4]u8, port: u16) !std.posix.fd_t {
    const fd = std.c.socket(
        std.c.AF.INET,
        std.c.SOCK.DGRAM,
        std.c.IPPROTO.UDP,
    );
    if (fd < 0) return error.SocketSetupFailed;
    errdefer closeFd(fd);
    try configureSocket(fd);
    try configureUdpBuffers(fd);
    const address = socketAddress4(.{ .ip = ip, .port = port });
    for (0..syscall_retry_max) |_| {
        const result = std.c.bind(
            fd,
            @ptrCast(&address),
            @sizeOf(std.c.sockaddr.in),
        );
        if (result == 0) return fd;
        if (std.c.errno(result) == .INTR) continue;
        return error.BindFailed;
    }
    return error.SyscallRetryLimitExceeded;
}

