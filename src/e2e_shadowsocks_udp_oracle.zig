fn createTcpSocket() !std.posix.fd_t {
    const fd = std.c.socket(
        std.c.AF.INET,
        std.c.SOCK.STREAM,
        std.c.IPPROTO.TCP,
    );
    if (fd < 0) return error.SocketSetupFailed;
    errdefer closeFd(fd);
    try configureSocket(fd);
    return fd;
}

fn closeFd(fd: std.posix.fd_t) void {
    if (fd < 0) return;
    const result = std.c.close(fd);
    if (result == 0) return;
    // POSIX leaves descriptor state unspecified on EINTR; retrying can close a
    // reused descriptor, so every close outcome is terminal and handled once.
    switch (std.c.errno(result)) {
        .INTR, .BADF, .IO => return,
        else => return,
    }
}

fn socketName4(fd: std.posix.fd_t) !Endpoint4 {
    var address = std.mem.zeroes(std.c.sockaddr.in);
    var address_len: std.c.socklen_t = @sizeOf(std.c.sockaddr.in);
    for (0..syscall_retry_max) |_| {
        const result = std.c.getsockname(
            fd,
            @ptrCast(&address),
            &address_len,
        );
        if (result == 0) break;
        if (std.c.errno(result) == .INTR) continue;
        return error.GetSocketNameFailed;
    } else return error.SyscallRetryLimitExceeded;
    if (address_len < @sizeOf(std.c.sockaddr.in)) {
        return error.InvalidSocketAddress;
    }
    if (address.family != std.c.AF.INET) return error.InvalidSocketAddress;
    return .{
        .ip = std.mem.asBytes(&address.addr)[0..4].*,
        .port = std.mem.bigToNative(u16, address.port),
    };
}

