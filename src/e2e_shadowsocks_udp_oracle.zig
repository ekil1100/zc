fn probeCapacity(
    io: std.Io,
    mixed_port: u16,
    deadline: Deadline,
) !void {
    var control_fds: [association_count_max]std.posix.fd_t =
        @splat(-1);
    defer {
        for (control_fds) |fd| closeFd(fd);
    }

    for (&control_fds) |*fd| {
        const association = try openAssociation(io, mixed_port, deadline);
        fd.* = association.fd;
    }

    const rejected = try establishAssociation(io, mixed_port, deadline);
    defer closeFd(rejected.fd);
    if (rejected.rep != 0x01) return error.UnexpectedCapacityReply;

    try completeControlTeardown(io, &control_fds[0], deadline);
    for (0..syscall_retry_max) |_| {
        const candidate = try establishAssociation(io, mixed_port, deadline);
        if (candidate.rep == 0) {
            if (candidate.relay == null) {
                closeFd(candidate.fd);
                return error.InvalidAssociateReply;
            }
            control_fds[0] = candidate.fd;
            return;
        }
        closeFd(candidate.fd);
        if (candidate.rep != 0x01) return error.UnexpectedCapacityReply;
        const remaining_ms = deadline.remaining(io) catch
            return error.CapacitySlotNotReleased;
        try std.Io.sleep(
            io,
            .fromMilliseconds(@intCast(@min(remaining_ms, 5))),
            .awake,
        );
    }
    return error.CapacitySlotNotReleased;
}
