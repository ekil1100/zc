const ReceivedDatagram = struct {
    size: usize,
    sender: Endpoint4,
};

fn receiveDatagram(
    fd: std.posix.fd_t,
    output: []u8,
) !ReceivedDatagram {
    const flags: c_int = if (@hasDecl(std.c.MSG, "TRUNC"))
        @intCast(std.c.MSG.TRUNC)
    else
        0;
    for (0..syscall_retry_max) |_| {
        var address = std.mem.zeroes(std.c.sockaddr.in);
        var address_len: std.c.socklen_t = @sizeOf(std.c.sockaddr.in);
        const result = std.c.recvfrom(
            fd,
            output.ptr,
            output.len,
            flags,
            @ptrCast(&address),
            &address_len,
        );
        if (result >= 0) {
            if (address_len < @sizeOf(std.c.sockaddr.in)) {
                return error.PacketDropped;
            }
            if (address.family != std.c.AF.INET) return error.PacketDropped;
            return .{
                .size = @intCast(result),
                .sender = .{
                    .ip = std.mem.asBytes(&address.addr)[0..4].*,
                    .port = std.mem.bigToNative(u16, address.port),
                },
            };
        }
        switch (std.c.errno(result)) {
            .INTR => continue,
            .AGAIN => return error.WouldBlock,
            .MSGSIZE => return error.DatagramTooLarge,
            .CONNREFUSED,
            .CONNRESET,
            .HOSTUNREACH,
            .NETUNREACH,
            .NOBUFS,
            .NOMEM,
            .PIPE,
            .TIMEDOUT,
            => return error.PacketDropped,
            else => return error.ReceiveFailed,
        }
    }
    return error.SyscallRetryLimitExceeded;
}

