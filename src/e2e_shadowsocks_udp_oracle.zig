fn endpointEqual(left: Endpoint4, right: Endpoint4) bool {
    return left.port == right.port and std.mem.eql(u8, &left.ip, &right.ip);
}

fn receiveRelayResponse(
    io: std.Io,
    fd: std.posix.fd_t,
    output: []u8,
    deadline: Deadline,
) !ReceivedDatagram {
    const events = try waitFd(io, fd, std.posix.POLL.IN, deadline);
    if (events == 0) return error.DeadlineExceeded;
    return receiveDatagram(fd, output);
}

fn expectNoResponse(
    io: std.Io,
    fd: std.posix.fd_t,
    deadline: Deadline,
) !void {
    var unexpected: [receive_size_max]u8 = undefined;
    for (0..syscall_retry_max) |_| {
        const events = try waitFd(io, fd, std.posix.POLL.IN, deadline);
        if (events == 0) return;
        _ = receiveDatagram(fd, &unexpected) catch |err| {
            if (packetIoRecoverable(err)) continue;
            return err;
        };
        return error.UnexpectedUdpResponse;
    }
    return error.SyscallRetryLimitExceeded;
}

fn drainNoResponseFd(fd: std.posix.fd_t, buffer: []u8) !void {
    _ = receiveDatagram(fd, buffer) catch |err| {
        if (packetIoRecoverable(err)) return;
        return err;
    };
    return error.UnexpectedUdpResponse;
}

fn expectNoResponsePair(
    io: std.Io,
    first_fd: std.posix.fd_t,
    second_fd: std.posix.fd_t,
    deadline: Deadline,
) !void {
    var unexpected: [receive_size_max]u8 = undefined;
    for (0..syscall_retry_max) |_| {
        const events = try waitFdPair(io, first_fd, second_fd, deadline);
        if (events[0] == 0 and events[1] == 0) return;
        if (events[0] != 0) try drainNoResponseFd(first_fd, &unexpected);
        if (events[1] != 0) try drainNoResponseFd(second_fd, &unexpected);
    }
    return error.SyscallRetryLimitExceeded;
}

