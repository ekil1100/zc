const Cipher = enum {
    aes_128_gcm,
    aes_256_gcm,
    chacha20_ietf_poly1305,

    fn parse(text: []const u8) ?Cipher {
        if (std.mem.eql(u8, text, "aes-128-gcm")) return .aes_128_gcm;
        if (std.mem.eql(u8, text, "aes-256-gcm")) return .aes_256_gcm;
        if (std.mem.eql(u8, text, "chacha20-ietf-poly1305")) {
            return .chacha20_ietf_poly1305;
        }
        return null;
    }

    fn keyLen(self: Cipher) usize {
        return switch (self) {
            .aes_128_gcm => 16,
            .aes_256_gcm, .chacha20_ietf_poly1305 => 32,
        };
    }

    fn saltLen(self: Cipher) usize {
        return self.keyLen();
    }
};

const DatagramCrypto = struct {
    cipher: Cipher,
    master_key: [32]u8,

    fn init(cipher: Cipher, password: []const u8) DatagramCrypto {
        return .{
            .cipher = cipher,
            .master_key = deriveMasterKey(password, cipher.keyLen()),
        };
    }

    fn deinit(self: *DatagramCrypto) void {
        std.crypto.secureZero(u8, &self.master_key);
        self.* = undefined;
    }

    fn sealRandom(
        self: *const DatagramCrypto,
        io: std.Io,
        plaintext: []const u8,
        output: []u8,
    ) ![]u8 {
        var salt_storage: [32]u8 = undefined;
        defer std.crypto.secureZero(u8, &salt_storage);
        const salt = salt_storage[0..self.cipher.saltLen()];
        try std.Io.randomSecure(io, salt);
        return self.sealWithSalt(plaintext, salt, output);
    }

    fn sealWithSalt(
        self: *const DatagramCrypto,
        plaintext: []const u8,
        salt: []const u8,
        output: []u8,
    ) ![]u8 {
        const salt_len = self.cipher.saltLen();
        if (salt.len != salt_len) return error.InvalidSalt;
        const plaintext_end = std.math.add(
            usize,
            salt_len,
            plaintext.len,
        ) catch return error.DatagramTooLarge;
        const wire_len = std.math.add(
            usize,
            plaintext_end,
            tag_size,
        ) catch return error.DatagramTooLarge;
        if (wire_len > wire_size_max) return error.DatagramTooLarge;
        if (output.len < wire_len) return error.OutputTooSmall;

        @memcpy(output[0..salt_len], salt);
        @memcpy(output[salt_len..plaintext_end], plaintext);
        var subkey = [_]u8{0} ** 32;
        defer std.crypto.secureZero(u8, &subkey);
        self.deriveSubkey(salt, &subkey);
        const ciphertext = output[salt_len..plaintext_end];
        const tag: *[tag_size]u8 = output[plaintext_end..wire_len][0..tag_size];
        encrypt(self.cipher, ciphertext, tag, &subkey);
        return output[0..wire_len];
    }

    fn open(
        self: *const DatagramCrypto,
        wire: []const u8,
        output: []u8,
    ) ![]u8 {
        if (wire.len > wire_size_max) return error.DatagramTooLarge;
        const salt_len = self.cipher.saltLen();
        const overhead = std.math.add(
            usize,
            salt_len,
            tag_size,
        ) catch return error.InvalidPacket;
        if (wire.len < overhead) return error.InvalidPacket;
        const ciphertext_end = wire.len - tag_size;
        const plaintext_len = ciphertext_end - salt_len;
        if (output.len < plaintext_len) return error.OutputTooSmall;

        var tag: [tag_size]u8 = undefined;
        @memcpy(&tag, wire[ciphertext_end..]);
        @memcpy(output[0..plaintext_len], wire[salt_len..ciphertext_end]);
        var subkey = [_]u8{0} ** 32;
        defer std.crypto.secureZero(u8, &subkey);
        self.deriveSubkey(wire[0..salt_len], &subkey);
        try decrypt(
            self.cipher,
            output[0..plaintext_len],
            tag,
            &subkey,
        );
        return output[0..plaintext_len];
    }

    fn deriveSubkey(
        self: *const DatagramCrypto,
        salt: []const u8,
        subkey: *[32]u8,
    ) void {
        const HmacSha1 = std.crypto.auth.hmac.HmacSha1;
        const HkdfSha1 = std.crypto.kdf.hkdf.Hkdf(HmacSha1);
        const key_len = self.cipher.keyLen();
        var prk = HkdfSha1.extract(salt, self.master_key[0..key_len]);
        defer std.crypto.secureZero(u8, &prk);
        subkey.* = @splat(0);
        HkdfSha1.expand(subkey[0..key_len], "ss-subkey", prk);
    }

    fn encrypt(
        cipher: Cipher,
        text: []u8,
        tag: *[tag_size]u8,
        subkey: *const [32]u8,
    ) void {
        const nonce = [_]u8{0} ** nonce_size;
        switch (cipher) {
            .aes_128_gcm => std.crypto.aead.aes_gcm.Aes128Gcm.encrypt(
                text,
                tag,
                text,
                "",
                nonce,
                subkey[0..16].*,
            ),
            .aes_256_gcm => std.crypto.aead.aes_gcm.Aes256Gcm.encrypt(
                text,
                tag,
                text,
                "",
                nonce,
                subkey.*,
            ),
            .chacha20_ietf_poly1305 => {
                std.crypto.aead.chacha_poly.ChaCha20Poly1305.encrypt(
                    text,
                    tag,
                    text,
                    "",
                    nonce,
                    subkey.*,
                );
            },
        }
    }

    fn decrypt(
        cipher: Cipher,
        text: []u8,
        tag: [tag_size]u8,
        subkey: *const [32]u8,
    ) !void {
        const nonce = [_]u8{0} ** nonce_size;
        switch (cipher) {
            .aes_128_gcm => std.crypto.aead.aes_gcm.Aes128Gcm.decrypt(
                text,
                text,
                tag,
                "",
                nonce,
                subkey[0..16].*,
            ) catch return error.AuthenticationFailed,
            .aes_256_gcm => std.crypto.aead.aes_gcm.Aes256Gcm.decrypt(
                text,
                text,
                tag,
                "",
                nonce,
                subkey.*,
            ) catch return error.AuthenticationFailed,
            .chacha20_ietf_poly1305 => {
                std.crypto.aead.chacha_poly.ChaCha20Poly1305.decrypt(
                    text,
                    text,
                    tag,
                    "",
                    nonce,
                    subkey.*,
                ) catch return error.AuthenticationFailed;
            },
        }
    }
};

fn deriveMasterKey(password: []const u8, key_len: usize) [32]u8 {
    std.debug.assert(key_len == 16 or key_len == 32);
    var key = [_]u8{0} ** 32;
    var previous: [16]u8 = undefined;
    defer std.crypto.secureZero(u8, &previous);
    var offset: usize = 0;
    for (0..2) |round| {
        if (offset >= key_len) break;
        var md5 = std.crypto.hash.Md5.init(.{});
        if (round > 0) md5.update(&previous);
        md5.update(password);
        md5.final(&previous);
        const copy_len = @min(previous.len, key_len - offset);
        @memcpy(key[offset .. offset + copy_len], previous[0..copy_len]);
        offset += copy_len;
    }
    std.debug.assert(offset == key_len);
    return key;
}

const AddressKind = enum {
    ipv4,
    domain,
    ipv6,
};

const ParsedAddress = struct {
    kind: AddressKind,
    host: []const u8,
    port: u16,
    raw: []const u8,
};

const AddressPayload = struct {
    address: ParsedAddress,
    payload: []const u8,
};

fn parseAddressPayload(input: []const u8) !AddressPayload {
    if (input.len < 1) return error.TruncatedAddress;
    const address_len: usize = switch (input[0]) {
        0x01 => 1 + 4 + 2,
        0x03 => length: {
            if (input.len < 2) return error.TruncatedAddress;
            const domain_len: usize = input[1];
            if (domain_len == 0) return error.InvalidDomainLength;
            break :length std.math.add(
                usize,
                1 + 1 + 2,
                domain_len,
            ) catch return error.TruncatedAddress;
        },
        0x04 => 1 + 16 + 2,
        else => return error.InvalidAddressType,
    };
    if (address_len > address_size_max) return error.AddressTooLong;
    if (input.len < address_len) return error.TruncatedAddress;

    const host = switch (input[0]) {
        0x01 => input[1..5],
        0x03 => input[2 .. 2 + @as(usize, input[1])],
        0x04 => input[1..17],
        else => unreachable,
    };
    const port = std.mem.readInt(
        u16,
        input[address_len - 2 ..][0..2],
        .big,
    );
    return .{
        .address = .{
            .kind = switch (input[0]) {
                0x01 => .ipv4,
                0x03 => .domain,
                0x04 => .ipv6,
                else => unreachable,
            },
            .host = host,
            .port = port,
            .raw = input[0..address_len],
        },
        .payload = input[address_len..],
    };
}

fn parseSocksUdp(input: []const u8) !AddressPayload {
    if (input.len > wire_size_max) return error.DatagramTooLarge;
    if (input.len < 3) return error.TruncatedSocksDatagram;
    if (input[0] != 0 or input[1] != 0) return error.ReservedNotZero;
    if (input[2] != 0) return error.FragmentationNotSupported;
    return parseAddressPayload(input[3..]);
}

const Endpoint4 = struct {
    ip: [4]u8,
    port: u16,
};

const Endpoint6 = struct {
    ip: [16]u8,
    port: u16,
};

fn buildSocksUdpIpv4(
    output: []u8,
    target: Endpoint4,
    payload: []const u8,
) ![]u8 {
    const header_len: usize = 3 + 1 + 4 + 2;
    const total_len = std.math.add(
        usize,
        header_len,
        payload.len,
    ) catch return error.DatagramTooLarge;
    if (total_len > wire_size_max) return error.DatagramTooLarge;
    if (output.len < total_len) return error.OutputTooSmall;
    output[0..10].* = .{
        0,
        0,
        0,
        1,
        target.ip[0],
        target.ip[1],
        target.ip[2],
        target.ip[3],
        @intCast(target.port >> 8),
        @intCast(target.port & 0xff),
    };
    @memcpy(output[header_len..total_len], payload);
    return output[0..total_len];
}

fn buildSocksUdpIpv6(
    output: []u8,
    target: Endpoint6,
    payload: []const u8,
) ![]u8 {
    const header_len: usize = 3 + 1 + 16 + 2;
    const total_len = std.math.add(
        usize,
        header_len,
        payload.len,
    ) catch return error.DatagramTooLarge;
    if (total_len > wire_size_max) return error.DatagramTooLarge;
    if (output.len < total_len) return error.OutputTooSmall;
    @memset(output[0..3], 0);
    output[3] = 4;
    @memcpy(output[4..20], &target.ip);
    output[20] = @intCast(target.port >> 8);
    output[21] = @intCast(target.port & 0xff);
    @memcpy(output[header_len..total_len], payload);
    return output[0..total_len];
}

fn buildSocksUdpDomain(
    output: []u8,
    domain: []const u8,
    port: u16,
    payload: []const u8,
) ![]u8 {
    if (domain.len == 0 or domain.len > domain_size_max) {
        return error.InvalidDomainLength;
    }
    const address_len = std.math.add(
        usize,
        1 + 1 + 2,
        domain.len,
    ) catch return error.DatagramTooLarge;
    const payload_start = std.math.add(
        usize,
        3,
        address_len,
    ) catch return error.DatagramTooLarge;
    const total_len = std.math.add(
        usize,
        payload_start,
        payload.len,
    ) catch return error.DatagramTooLarge;
    if (total_len > wire_size_max) return error.DatagramTooLarge;
    if (output.len < total_len) return error.OutputTooSmall;

    output[0..5].* = .{ 0, 0, 0, 3, @intCast(domain.len) };
    @memcpy(output[5 .. 5 + domain.len], domain);
    output[payload_start - 2] = @intCast(port >> 8);
    output[payload_start - 1] = @intCast(port & 0xff);
    @memcpy(output[payload_start..total_len], payload);
    return output[0..total_len];
}

fn parseAssociateReply(reply: []const u8) !Endpoint4 {
    if (reply.len != 10) return error.InvalidAssociateReply;
    if (reply[0] != 5 or reply[2] != 0) return error.InvalidAssociateReply;
    if (reply[1] != 0) return error.AssociateRejected;
    if (reply[3] != 1) return error.NonIpv4AssociateReply;
    const port = std.mem.readInt(u16, reply[8..10], .big);
    if (port == 0) return error.InvalidAssociateReply;
    return .{
        .ip = reply[4..8].*,
        .port = port,
    };
}

fn mainServe(io: std.Io, args: []const []const u8) !void {
    if (args.len != 6 and args.len != 7) return error.InvalidArguments;
    const cipher = Cipher.parse(args[2]) orelse return error.InvalidArguments;
    const password = args[3];
    if (password.len == 0 or password.len > password_size_max) {
        return error.InvalidArguments;
    }
    const mode: ServeMode = if (std.mem.eql(u8, args[4], "normal"))
        .normal
    else if (std.mem.eql(u8, args[4], "bad-tag-once"))
        .bad_tag_once
    else if (std.mem.eql(u8, args[4], "truncated-salt-once"))
        .truncated_salt_once
    else if (std.mem.eql(u8, args[4], "truncated-tag-once"))
        .truncated_tag_once
    else
        return error.InvalidArguments;
    const endpoint_id = args[5];
    if (!validEndpointId(endpoint_id)) return error.InvalidArguments;
    const port = if (args.len == 7) try parsePortAllowZero(args[6]) else 0;
    try serveOracle(io, cipher, password, mode, endpoint_id, port);
}

