}

fn mainProbe(io: std.Io, args: []const []const u8) ![]const u8 {
    if (args.len < 4) return error.InvalidArguments;
    const deadline = Deadline.after(io, probe_lifetime_ms);
    const probe_kind = parseProbeKind(args[2]) orelse return error.InvalidArguments;
    switch (probe_kind) {
        .roundtrip,
        .roundtrip_domain,
        .roundtrip_ipv6,
        .response_drop_recovery,
        .source_pin,
        .client_ip,
        .control_close,
        .selection_teardown,
        => {
            if (args.len != 6) return error.InvalidArguments;
            const mixed_port = try parsePort(args[3]);
            const target_port = try parsePort(args[4]);
            try validateNonceArgument(args[5]);
            switch (probe_kind) {
                .roundtrip => try probeRoundtrip(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .roundtrip_domain => try probeRoundtripDomain(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .roundtrip_ipv6 => try probeRoundtripIpv6(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .response_drop_recovery => try probeResponseDropRecovery(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .source_pin => try probeSourcePin(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .client_ip => try probeClientIp(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .control_close => try probeControlClose(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                .selection_teardown => try probeSelectionTeardown(
                    io,
                    mixed_port,
                    target_port,
                    args[5],
                    deadline,
                ),
                else => unreachable,
            }
            return args[2];
        },
        .invalid_then_valid => {
            if (args.len != 7) return error.InvalidArguments;
            const invalid_kind = parseInvalidKind(args[3]) orelse
                return error.InvalidArguments;
            const mixed_port = try parsePort(args[4]);
            const target_port = try parsePort(args[5]);
            try validateNonceArgument(args[6]);
            try probeInvalidThenValid(
                io,
                invalid_kind,
                mixed_port,
                target_port,
                args[6],
                deadline,
            );
            return "invalid-then-valid";
        },
        .associate_rejected => {
            if (args.len != 5) return error.InvalidArguments;
            try probeAssociateRejected(
                io,
                try parsePort(args[3]),
                try parseReplyCode(args[4]),
                deadline,
            );
            return "associate-rejected";
        },
        .max => {
            if (args.len != 7) return error.InvalidArguments;
            const cipher = Cipher.parse(args[3]) orelse
                return error.InvalidArguments;
            const mixed_port = try parsePort(args[4]);
            const target_port = try parsePort(args[5]);
            try validateNonceArgument(args[6]);
            try probeMax(
                io,
                cipher,
                mixed_port,
                target_port,
                args[6],
                deadline,
            );
            return "max";
        },
        .capacity => {
            if (args.len != 4) return error.InvalidArguments;
            try probeCapacity(io, try parsePort(args[3]), deadline);
            return "capacity";
        },
    }
}

fn parseProbeKind(text: []const u8) ?ProbeKind {
    if (std.mem.eql(u8, text, "roundtrip")) return .roundtrip;
    if (std.mem.eql(u8, text, "roundtrip-domain")) return .roundtrip_domain;
    if (std.mem.eql(u8, text, "roundtrip-ipv6")) return .roundtrip_ipv6;
    if (std.mem.eql(u8, text, "response-drop-recovery")) {
        return .response_drop_recovery;
    }
    if (std.mem.eql(u8, text, "invalid-then-valid")) {
        return .invalid_then_valid;
    }
    if (std.mem.eql(u8, text, "source-pin")) return .source_pin;
    if (std.mem.eql(u8, text, "client-ip")) return .client_ip;
    if (std.mem.eql(u8, text, "control-close")) return .control_close;
    if (std.mem.eql(u8, text, "selection-teardown")) {
        return .selection_teardown;
    }
    if (std.mem.eql(u8, text, "associate-rejected")) {
        return .associate_rejected;
    }
    if (std.mem.eql(u8, text, "max")) return .max;
    if (std.mem.eql(u8, text, "capacity")) return .capacity;
    return null;
}

fn parseInvalidKind(text: []const u8) ?InvalidKind {
    if (std.mem.eql(u8, text, "rsv1")) return .rsv1;
    if (std.mem.eql(u8, text, "rsv2")) return .rsv2;
    if (std.mem.eql(u8, text, "frag")) return .frag;
    if (std.mem.eql(u8, text, "atyp")) return .atyp;
    if (std.mem.eql(u8, text, "truncated")) return .truncated;
    return null;
}

fn parseReplyCode(text: []const u8) !u8 {
    if (text.len == 0 or text.len > 3) return error.InvalidArguments;
    for (text) |byte| {
        if (!std.ascii.isDigit(byte)) return error.InvalidArguments;
    }
    return std.fmt.parseInt(u8, text, 10) catch
        return error.InvalidArguments;
}

fn parsePort(text: []const u8) !u16 {
    const port = try parsePortAllowZero(text);
    if (port == 0) return error.InvalidArguments;
    return port;
}

fn parsePortAllowZero(text: []const u8) !u16 {
    if (text.len == 0 or text.len > 5) return error.InvalidArguments;
    for (text) |byte| {
        if (!std.ascii.isDigit(byte)) return error.InvalidArguments;
    }
    return std.fmt.parseInt(u16, text, 10) catch
        return error.InvalidArguments;
}

fn validateNonceArgument(nonce: []const u8) !void {
    if (nonce.len == 0 or nonce.len > nonce_argument_size_max) {
        return error.InvalidArguments;
    }
}

fn validEndpointId(text: []const u8) bool {
    if (text.len == 0 or text.len > 32) return false;
    for (text) |byte| {
        if (std.ascii.isAlphanumeric(byte) or byte == '-' or byte == '_') {
            continue;
        }
        return false;
    }
    return true;
}

fn printLine(
    io: std.Io,
    comptime format: []const u8,
    arguments: anytype,
) !void {
    var buffer: [512]u8 = undefined;
    const line = try std.fmt.bufPrint(&buffer, format, arguments);
    // Streaming writes bypass seek-positioned buffering, so every marker is
    // visible immediately even when stdout is redirected to a regular file.
    try std.Io.File.stdout().writeStreamingAll(io, line);
}

fn serveOracle(
    io: std.Io,
    cipher: Cipher,
    password: []const u8,
    mode: ServeMode,
    endpoint_id: []const u8,
    requested_port: u16,
) !void {
    const fd = try createUdpSocket(requested_port);
    defer closeFd(fd);
    const endpoint = try socketName4(fd);
    try printLine(
        io,
        "E2E_SS_UDP_ORACLE_READY={s}:{d}\n",
        .{ endpoint_id, endpoint.port },
    );

    var crypto = DatagramCrypto.init(cipher, password);
    defer crypto.deinit();
    var receive_buffer: [receive_size_max]u8 = undefined;
    var plaintext_buffer: [wire_size_max]u8 = undefined;
    var response_buffer: [wire_size_max]u8 = undefined;
    const lifetime_deadline = Deadline.after(io, service_lifetime_ms);
    var pending_response: ?ResponseKind = switch (mode) {
        .normal => null,
        .bad_tag_once => .bad_tag,
        .truncated_salt_once => .truncated_salt,
        .truncated_tag_once => .truncated_tag,
    };

    var packet_count: u32 = 0;
    while (packet_count < packet_count_max) : (packet_count += 1) {
        const events = try waitFd(
            io,
            fd,
            std.posix.POLL.IN,
            lifetime_deadline,
        );
        if (events == 0) return;
        const received = receiveDatagram(fd, &receive_buffer) catch |err| {
            if (packetIoRecoverable(err)) continue;
            return err;
        };
        const raw_count = packet_count + 1;
        try printLine(
            io,
            "E2E_SS_UDP_ORACLE_RAW={s}:{d}\n",
            .{ endpoint_id, raw_count },
        );
        if (received.size > wire_size_max) continue;

        const plaintext = crypto.open(
            receive_buffer[0..received.size],
            &plaintext_buffer,
        ) catch continue;
        _ = parseAddressPayload(plaintext) catch continue;
        try printLine(
            io,
            "E2E_SS_UDP_ORACLE_VERIFIED={s}:{d}\n",
            .{ endpoint_id, raw_count },
        );

        const response = try crypto.sealRandom(
            io,
            plaintext,
            &response_buffer,
        );
        const response_kind = pending_response orelse .normal;
        const sent_response: []const u8 = switch (response_kind) {
            .normal => response,
            .bad_tag => corrupted: {
                std.debug.assert(response.len >= tag_size);
                response[response.len - 1] ^= 0x01;
                break :corrupted response;
            },
            .truncated_salt => response[0 .. crypto.cipher.saltLen() - 1],
            .truncated_tag => response[0 .. response.len - 1],
        };
        sendDatagram(
            io,
            fd,
            sent_response,
            received.sender,
            lifetime_deadline,
        ) catch |err| {
            if (packetIoRecoverable(err)) continue;
            return err;
        };
        if (response_kind != .normal) pending_response = null;
        try printLine(
            io,
            "E2E_SS_UDP_ORACLE_RESPONSE={s}:{d}:{s}\n",
            .{ endpoint_id, raw_count, response_kind.marker() },
        );
    }
}

