fn discoverNonLoopbackIpv4() ![4]u8 {
    const fd = std.c.socket(
        std.c.AF.INET,
        std.c.SOCK.DGRAM,
        std.c.IPPROTO.UDP,
    );
    if (fd < 0) return error.SocketSetupFailed;
    defer closeFd(fd);
    try configureSocket(fd);
    const probe = socketAddress4(.{
        .ip = .{ 192, 0, 2, 1 },
        .port = 9,
    });
    for (0..syscall_retry_max) |_| {
        const result = std.c.connect(
            fd,
            @ptrCast(&probe),
            @sizeOf(std.c.sockaddr.in),
        );
        if (result == 0) break;
        if (std.c.errno(result) == .INTR) continue;
