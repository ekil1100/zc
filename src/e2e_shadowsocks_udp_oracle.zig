fn packetIoRecoverable(err: anyerror) bool {
    return switch (err) {
        error.WouldBlock,
        error.DatagramTooLarge,
        error.PacketDropped,
        => true,
        else => false,
    };
}

fn connectTcpLoopback(
    io: std.Io,
    port: u16,
    deadline: Deadline,
) !std.posix.fd_t {
    const fd = try createTcpSocket();
    errdefer closeFd(fd);
    const address = socketAddress4(.{
        .ip = .{ 127, 0, 0, 1 },
        .port = port,
    });
    for (0..syscall_retry_max) |_| {
        const result = std.c.connect(
            fd,
            @ptrCast(&address),
            @sizeOf(std.c.sockaddr.in),
        );
        if (result == 0) return fd;
        switch (std.c.errno(result)) {
            .INTR => continue,
            .ISCONN => return fd,
            .INPROGRESS, .ALREADY, .AGAIN => break,
            .CONNREFUSED => return error.ConnectionRefused,
            else => return error.ConnectFailed,
        }
    } else return error.SyscallRetryLimitExceeded;

    const events = try waitFd(io, fd, std.posix.POLL.OUT, deadline);
    if (events == 0) return error.DeadlineExceeded;
    var socket_error: c_int = 0;
    var socket_error_len: std.c.socklen_t = @sizeOf(c_int);
    if (std.c.getsockopt(
        fd,
        std.c.SOL.SOCKET,
        std.c.SO.ERROR,
        &socket_error,
        &socket_error_len,
    ) != 0) return error.ConnectFailed;
    if (socket_error != 0) return error.ConnectFailed;
    return fd;
}

fn sendStreamAll(
    io: std.Io,
    fd: std.posix.fd_t,
    bytes: []const u8,
    deadline: Deadline,
) !void {
    const flags: c_int = if (@hasDecl(std.c.MSG, "NOSIGNAL"))
        @intCast(std.c.MSG.NOSIGNAL)
    else
        0;
    var offset: usize = 0;
    var iteration: usize = 0;
    while (offset < bytes.len and iteration < stream_io_iteration_max) : (iteration += 1) {
        const events = try waitFd(io, fd, std.posix.POLL.OUT, deadline);
        if (events == 0) return error.DeadlineExceeded;
        const result = std.c.send(
            fd,
            bytes[offset..].ptr,
            bytes.len - offset,
            flags,
        );
        if (result > 0) {
            offset = std.math.add(
                usize,
                offset,
                @intCast(result),
            ) catch return error.StreamWriteFailed;
            continue;
        }
        if (result == 0) return error.StreamWriteZero;
        switch (std.c.errno(result)) {
            .INTR, .AGAIN => continue,
            .PIPE => return error.BrokenPipe,
            .CONNRESET => return error.ConnectionReset,
            else => return error.StreamWriteFailed,
        }
    }
    if (offset != bytes.len) return error.StreamIterationLimitExceeded;
}

fn receiveStreamExact(
    io: std.Io,
    fd: std.posix.fd_t,
    output: []u8,
    deadline: Deadline,
) !void {
    var offset: usize = 0;
    var iteration: usize = 0;
    while (offset < output.len and iteration < stream_io_iteration_max) : (iteration += 1) {
        const events = try waitFd(io, fd, std.posix.POLL.IN, deadline);
        if (events == 0) return error.DeadlineExceeded;
        const result = std.c.recv(
            fd,
            output[offset..].ptr,
            output.len - offset,
            0,
        );
        if (result > 0) {
            offset = std.math.add(
                usize,
                offset,
                @intCast(result),
            ) catch return error.StreamReadFailed;
            continue;
        }
        if (result == 0) return error.UnexpectedEof;
        switch (std.c.errno(result)) {
            .INTR, .AGAIN => continue,
            .CONNRESET => return error.ConnectionReset,
            else => return error.StreamReadFailed,
        }
    }
    if (offset != output.len) return error.StreamIterationLimitExceeded;
}

fn shutdownControlWrite(fd: std.posix.fd_t) !void {
    for (0..syscall_retry_max) |_| {
        const result = std.c.shutdown(fd, std.c.SHUT.WR);
        if (result == 0) return;
        switch (std.c.errno(result)) {
            .INTR => continue,
            .NOTCONN => return,
            else => return error.ControlShutdownFailed,
        }
    }
    return error.SyscallRetryLimitExceeded;
}

fn waitForControlEof(
    io: std.Io,
    fd: std.posix.fd_t,
    deadline: Deadline,
) !void {
    var byte: [1]u8 = undefined;
    for (0..syscall_retry_max) |_| {
        const events = try waitFd(io, fd, std.posix.POLL.IN, deadline);
        if (events == 0) return error.DeadlineExceeded;
        const result = std.c.recv(fd, &byte, byte.len, 0);
        if (result == 0) return;
        if (result > 0) return error.UnexpectedControlData;
        switch (std.c.errno(result)) {
            .INTR, .AGAIN => continue,
            .CONNRESET => return,
            else => return error.StreamReadFailed,
        }
    }
    return error.SyscallRetryLimitExceeded;
}

fn completeControlTeardown(
    io: std.Io,
    fd: *std.posix.fd_t,
    deadline: Deadline,
) !void {
    if (fd.* < 0) return;
    try shutdownControlWrite(fd.*);
    try waitForControlEof(io, fd.*, deadline);
    closeFd(fd.*);
    fd.* = -1;
}

const AssociationResult = struct {
    fd: std.posix.fd_t,
    rep: u8,
    relay: ?Endpoint4,
};

fn establishAssociation(
    io: std.Io,
    mixed_port: u16,
    deadline: Deadline,
) !AssociationResult {
    const fd = try connectTcpLoopback(io, mixed_port, deadline);
    errdefer closeFd(fd);

    try sendStreamAll(io, fd, &.{ 5, 1, 0 }, deadline);
    var greeting_reply: [2]u8 = undefined;
    try receiveStreamExact(io, fd, &greeting_reply, deadline);
    if (!std.mem.eql(u8, &greeting_reply, &.{ 5, 0 })) {
        return error.InvalidGreetingReply;
    }

    try sendStreamAll(
        io,
        fd,
        &.{ 5, 3, 0, 1, 0, 0, 0, 0, 0, 0 },
        deadline,
    );
    var reply: [10]u8 = undefined;
    try receiveStreamExact(io, fd, &reply, deadline);
    if (reply[0] != 5 or reply[2] != 0) {
        return error.InvalidAssociateReply;
    }
    if (reply[3] != 1) return error.NonIpv4AssociateReply;
    if (reply[1] != 0) {
        return .{ .fd = fd, .rep = reply[1], .relay = null };
    }
    return .{
        .fd = fd,
        .rep = 0,
        .relay = try parseAssociateReply(&reply),
    };
}

fn openAssociation(
    io: std.Io,
    mixed_port: u16,
    deadline: Deadline,
) !AssociationResult {
    const result = try establishAssociation(io, mixed_port, deadline);
    errdefer closeFd(result.fd);
    if (result.rep != 0) return error.AssociateRejected;
    const relay = result.relay orelse return error.InvalidAssociateReply;
    if (!std.mem.eql(u8, &relay.ip, &.{ 127, 0, 0, 1 })) {
        return error.NonLoopbackRelay;
    }
    return result;
}

fn validateRelayResponse(
    received: ReceivedDatagram,
    expected_relay: Endpoint4,
    bytes: []const u8,
    expected_target: Endpoint4,
    expected_payload: []const u8,
) !void {
    if (!endpointEqual(received.sender, expected_relay)) {
        return error.UnexpectedResponseSender;
    }
    if (received.size > bytes.len) return error.DatagramTooLarge;
    const parsed = try parseSocksUdp(bytes[0..received.size]);
    if (parsed.address.kind != .ipv4) return error.UnexpectedResponseAddress;
    if (!std.mem.eql(u8, parsed.address.host, &expected_target.ip)) {
        return error.UnexpectedResponseAddress;
    }
    if (parsed.address.port != expected_target.port) {
        return error.UnexpectedResponseAddress;
    }
    if (!std.mem.eql(u8, parsed.payload, expected_payload)) {
        return error.UnexpectedResponsePayload;
    }
}

