fn makeInvalidPacket(
    kind: InvalidKind,
    output: []u8,
    target: Endpoint4,
    payload: []const u8,
) ![]const u8 {
    const valid = try buildSocksUdpIpv4(output, target, payload);
    switch (kind) {
        .rsv1 => output[0] = 1,
        .rsv2 => output[1] = 1,
        .frag => output[2] = 1,
        .atyp => output[3] = 2,
        .truncated => return output[0..5],
    }
    return valid;
}

fn taggedPayload(
    output: []u8,
    nonce: []const u8,
    tag: []const u8,
) ![]const u8 {
    const total_len = std.math.add(
        usize,
        nonce.len,
        tag.len,
    ) catch return error.OutputTooSmall;
    if (total_len > output.len) return error.OutputTooSmall;
    @memcpy(output[0..nonce.len], nonce);
    @memcpy(output[nonce.len..total_len], tag);
    return output[0..total_len];
}

