test "Shadowsocks UDP oracle rejects bad tags and preserves packet recovery" {
    const literal = try decodeLiteralHex(
        "000102030405060708090a0b0c0d0e0f" ++
            "5f258e0c61142e2adf12b78447f4379ccad5b5fe1ca235e4cdd27f71ed4e3d816cc95508",
    );
    var crypto = DatagramCrypto.init(.aes_128_gcm, "password");
    defer crypto.deinit();
    var corrupted = literal;
    corrupted[corrupted.len - 1] ^= 0x01;
    var plaintext: [64]u8 = undefined;
    try std.testing.expectError(
        error.AuthenticationFailed,
        crypto.open(&corrupted, &plaintext),
    );
    const opened = try crypto.open(&literal, &plaintext);
    try std.testing.expectEqualSlices(
        u8,
        &(try decodeLiteralHex("030b6578616d706c652e636f6d003568656c6c6f")),
        opened,
    );
}

test "Shadowsocks UDP oracle enforces every cipher full wire and output boundary" {
    const ciphers = [_]Cipher{
        .aes_128_gcm,
        .aes_256_gcm,
        .chacha20_ietf_poly1305,
    };
    var plaintext: [wire_size_max + 1]u8 = @splat(0x5a);
    var output: [wire_size_max]u8 = undefined;
    var oversized: [wire_size_max + 1]u8 = @splat(0);
    const salt_storage = [_]u8{0x11} ** 32;

    for (ciphers) |cipher| {
        var crypto = DatagramCrypto.init(cipher, "password");
        defer crypto.deinit();
        const plaintext_len_max = wire_size_max - cipher.saltLen() - tag_size;
        const salt = salt_storage[0..cipher.saltLen()];
        const exact = try crypto.sealWithSalt(
            plaintext[0..plaintext_len_max],
            salt,
            &output,
        );
        try std.testing.expectEqual(@as(usize, wire_size_max), exact.len);
        try std.testing.expectError(
            error.DatagramTooLarge,
            crypto.sealWithSalt(
                plaintext[0 .. plaintext_len_max + 1],
                salt,
                &output,
            ),
        );
        try std.testing.expectError(
            error.OutputTooSmall,
            crypto.open(exact, plaintext[0 .. plaintext_len_max - 1]),
        );
        try std.testing.expectError(
            error.DatagramTooLarge,
            crypto.open(&oversized, &plaintext),
        );
    }
}

test "Shadowsocks UDP oracle parses address-prefixed plaintext independently" {
    const ipv4 = try parseAddressPayload("\x01\x7f\x00\x00\x01\x14\xe9ping");
    try std.testing.expectEqual(AddressKind.ipv4, ipv4.address.kind);
    try std.testing.expectEqual(@as(u16, 5353), ipv4.address.port);
    try std.testing.expectEqualSlices(u8, &.{ 127, 0, 0, 1 }, ipv4.address.host);
    try std.testing.expectEqualStrings("ping", ipv4.payload);

    const domain = try parseAddressPayload("\x03\x03dns\x00\x35query");
    try std.testing.expectEqual(AddressKind.domain, domain.address.kind);
    try std.testing.expectEqualStrings("dns", domain.address.host);
    try std.testing.expectEqualStrings("query", domain.payload);

    const ipv6 = try parseAddressPayload(
        "\x04\x00\x01\x02\x03\x04\x05\x06\x07" ++
            "\x08\x09\x0a\x0b\x0c\x0d\x0e\x0f\x01\xbbdata",
    );
    try std.testing.expectEqual(AddressKind.ipv6, ipv6.address.kind);
    try std.testing.expectEqual(@as(usize, 16), ipv6.address.host.len);
    try std.testing.expectEqualStrings("data", ipv6.payload);

    try std.testing.expectError(error.InvalidAddressType, parseAddressPayload("\x02x"));
    try std.testing.expectError(error.TruncatedAddress, parseAddressPayload("\x03\x05ab"));
}

