#[test]
fn cas_child_process() {
    let Some(root) = std::env::var_os("ZC_STORE_CAS_ROOT") else {
        return;
    };
    let store = Store::open(root).unwrap();
    let old = store.load().unwrap();
    // Both children are held behind a real filesystem barrier after observing sequence 7.
    let id = std::env::var("ZC_STORE_CHILD_ID").unwrap();
    std::fs::write(store.root_path().join(format!("ready-{id}")), b"").unwrap();
    let start = std::time::Instant::now();
    while !store.root_path().join("go").exists() {
        assert!(start.elapsed() < std::time::Duration::from_secs(10));
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
    let result = store.activate(&old.token, None);
    let value = match result {
        Ok(_) => "committed",
        Err(e)
            if e.downcast_ref::<zc::store::StoreError>()
                == Some(&zc::store::StoreError::Conflict) =>
        {
            "conflict"
        }
        Err(e) => panic!("unexpected error: {e}"),
    };
    std::fs::write(store.root_path().join(format!("result-{id}")), value).unwrap();
}

#[test]
fn actual_cross_process_writers_have_exactly_one_cas_winner() {
    let temp = tempfile::tempdir().unwrap();
    let root = temp.path().join("state");
    install_golden(&root);
    let spawn = |id: &str| {
        std::process::Command::new(std::env::current_exe().unwrap())
            .args(["--exact", "cas_child_process", "--nocapture"])
            .env("ZC_STORE_CAS_ROOT", &root)
            .env("ZC_STORE_CHILD_ID", id)
            .spawn()
            .unwrap()
    };
    let mut a = spawn("a");
    let mut b = spawn("b");
    let start = std::time::Instant::now();
    while !(root.join("ready-a").exists() && root.join("ready-b").exists()) {
        assert!(start.elapsed() < std::time::Duration::from_secs(10));
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
    std::fs::write(root.join("go"), b"").unwrap();
    assert!(a.wait().unwrap().success());
    assert!(b.wait().unwrap().success());
    let mut results = [
        std::fs::read_to_string(root.join("result-a")).unwrap(),
        std::fs::read_to_string(root.join("result-b")).unwrap(),
    ];
    results.sort();
    assert_eq!(results, ["committed", "conflict"]);
    assert_eq!(
        Store::open(&root).unwrap().load().unwrap().catalog.sequence,
        8
    );
}

