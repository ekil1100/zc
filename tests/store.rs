fn publishing_filters_selections_and_never_resurrects_removed_groups() {
    use zc::store::Selection;
    let temp = tempfile::tempdir().unwrap();
    let store = Store::open(temp.path().join("state")).unwrap();
    let source = b"mixed-port: 9000\nproxy-groups: [{name: Proxy, type: select, proxies: [DIRECT, REJECT]}]\nrules: ['MATCH,Proxy']\n";
    let bundle = Bundle::from_memory(source, None, Default::default()).unwrap();
    let receipt = store
        .publish(
            &store.load().unwrap().token,
            "home",
            None,
            &bundle,
            Metadata::default(),
            true,
        )
        .unwrap();
    let p = store.get("home").unwrap();
    store
        .select(
            &receipt.token,
            "home",
            &p.head,
            0,
            vec![Selection {
                group: "Proxy".into(),
                proxy: "REJECT".into(),
            }],
        )
        .unwrap();
    // Zig catalog_commands.zig filterSelections: removal -> generation 2;
    // restoring a group with no persisted selection keeps generation 2.
    for (source, sequence) in [
        (b"mixed-port: 9000\nrules: ['MATCH,DIRECT']\n".as_slice(), 3),
        (source.as_slice(), 4),
    ] {
        let before = store.load().unwrap();
        let bundle = Bundle::from_memory(source, None, Default::default()).unwrap();
        let receipt = store
            .publish(
                &before.token,
                "home",
                Some(&before.catalog.profiles[0].head),
                &bundle,
                Metadata::default(),
                true,
            )
            .unwrap();
        let after = store.load().unwrap();
        assert_eq!(after.token, receipt.token);
        assert_eq!(after.catalog.sequence, sequence);
        assert_eq!(after.catalog.profiles[0].desired.generation, 2);
        assert!(after.catalog.profiles[0].desired.selections.is_empty());
        assert_eq!(
            after.catalog.active.unwrap().revision,
            after.catalog.profiles[0].head
        );
    }
}

#[test]
fn runtime_capture_cannot_bypass_catalog_remote_admission() {
    let temp = tempfile::tempdir().unwrap();
    let source = temp.path().join("runtime.yaml");
    std::fs::write(&source, "mixed-port: 9000\nrule-providers: {remote: {type: http, behavior: domain, path: remote.yaml, url: 'https://example.com/rules'}}\nrules: ['RULE-SET,remote,DIRECT']\n").unwrap();
    let bundle = Bundle::capture_for_runtime(&source).unwrap();
    let store = Store::open(temp.path().join("state")).unwrap();
    for activate in [false, true] {
        assert!(
            store
                .publish(
                    &store.load().unwrap().token,
                    "home",
                    None,
                    &bundle,
                    Metadata::default(),
                    activate
                )
                .is_err()
        );
        assert!(!store.root_path().join("state-v2.json").exists());
        assert!(!store.root_path().join("profiles").exists());
    }
}
