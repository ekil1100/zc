fn selection_rename_delete_and_activation_are_cas_transactions() {
    use zc::store::Selection;
    let temp = tempfile::tempdir().unwrap();
    let root = temp.path().join("state");
    install_golden(&root);
    let store = Store::open(&root).unwrap();
    let before = store.load().unwrap();
    let selected = store
        .select(
            &before.token,
            "home",
            GOLDEN_REVISION,
            0,
            vec![Selection {
                group: "route".into(),
                proxy: "DIRECT".into(),
            }],
        )
        .unwrap();
    assert_eq!(store.get("home").unwrap().desired.generation, 1);
    assert!(
        store
            .select(&selected.token, "home", GOLDEN_REVISION, 0, vec![])
            .is_err()
    );
    let renamed = store
        .rename(&selected.token, "home", GOLDEN_REVISION, "office")
        .unwrap();
    let p = store.get("office").unwrap();
    assert_ne!(p.head, GOLDEN_REVISION);
    assert_eq!(p.desired.generation, 1);
    assert_eq!(store.load().unwrap().catalog.active.unwrap().key, "office");
    assert!(store.read_bundle("home", GOLDEN_REVISION).is_ok());
    let deactivated = store.activate(&renamed.token, None).unwrap();
    let activated = store.activate(&deactivated.token, Some("office")).unwrap();
    store.delete(&activated.token, "office", &p.head).unwrap();
    assert!(store.list().unwrap().is_empty());
    assert!(store.load().unwrap().catalog.active.is_none());
}

